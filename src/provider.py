# check for API key prefixes to detect provider
API_KEY_PREFIXES: tuple[tuple[str, str], ...] = (
    ("sk-ant-", "anthropic"),
    ("sk-or-", "openrouter"),
    ("gsk_", "groq"),
    ("AIza", "gemini"),
    ("xai-", "xai"),
    ("sk-", "openai"),  # supposing any other "sk-" prefix belongs to OpenAI
)


@dataclass(frozen=True)
class ToolCall:
    """Standardized tool/function call requested by the model"""

    id: str
    name: str
    arguments: dict[str, Any]


@dataclass(frozen=True)
class ProviderResponse:
    """Standardized response returned by an LLM call"""

    content: str
    model: str
    tool_calls: list[ToolCall] = field(default_factory=list)
    parsed: dict[str, Any] | BaseModel | None = None
    raw_message: dict[str, Any] = field(default_factory=dict)


@dataclass(frozen=True)
class StreamChunk:
    """Single incremental token delta yielded during streaming."""

    content: str = ""  # the next piece of content to render
    reasoning: str = ""  # thinking tokens generated by the model
    finish_reason: str | None = None


class Provider:
    """LLM-agnostic client backed by LiteLLM."""

    def __init__(
        self,
        api_key: str | None = None,
        model: str | None = None,
        provider: str | None = None,
        base_url: str | None = None,
    ) -> None:
        """Initialize the provider from an API key, model name, or environment.

        Args:
            api_key: Raw API key. If None, loaded from environment or  .env file
            model: Model identifier (e.g. "gpt-oss-120b" or "groq/openai/gpt-oss-120b").
                   If None, uses the detected provider's default model
            provider: Explicit provider name (needed when key has no known prefix
                      and model has no "<provider>/" prefix, e.g. Mistral)
            base_url: Optional custom endpoint URL (for local proxy / Ollama)
        """
        load_dotenv()
        self.base_url = base_url
        self.provider, self.model, self.api_key = self._resolve_config(
            api_key=api_key,
            model=model,
            provider=provider,
        )

    @staticmethod
    def detect_provider_from_key(api_key: str) -> str | None:
        """Infer the provider slug from well-known API key prefixes."""
        api_key = api_key.strip() if api_key else ""
        if not api_key:
            return None
        for prefix, provider in API_KEY_PREFIXES:
            if api_key.startswith(prefix):
                return provider
        return None

    @classmethod
    def _resolve_config(
        cls,
        api_key: str | None,
        model: str | None,
        provider: str | None,
    ) -> tuple[str, str, str]:
        """Resolve and validate `(provider, normalized_model, api_key)`."""

        clean_provider = provider.strip().lower() if provider and provider.strip() else None
        clean_model = model.strip() if model and model.strip() else None
        clean_api_key = api_key.strip() if api_key is not None else None

        if api_key is not None and not clean_api_key:
            raise ValueError("api_key cannot be empty.")

        model_provider = None
        if clean_model and "/" in clean_model:
            model_provider = clean_model.split("/", 1)[0].lower()
            if clean_provider and clean_provider != model_provider:
                raise ValueError(
                    f"Conflicting provider {clean_provider!r} and model prefix {model_provider!r}."
                )

        resolved_provider = clean_provider or model_provider
        if not resolved_provider and clean_api_key:
            resolved_provider = cls.detect_provider_from_key(clean_api_key)
        if not resolved_provider:
            for key_provider, config in PROVIDER_CONFIGS.items():
                if os.environ.get(config.env_var, "").strip():
                    resolved_provider = key_provider
                    break

        if not resolved_provider:
            raise ValueError(
                "Could not determine LLM provider. Pass an API key with a known prefix, "
                "specify `provider` or `model` (e.g. 'openai/gpt-4o-mini'), "
                "or set a provider API key environment variable."
            )

        config = PROVIDER_CONFIGS.get(resolved_provider)
        if clean_api_key is not None:
            resolved_api_key = clean_api_key
        else:
            env_var = config.env_var if config else f"{resolved_provider.upper()}_API_KEY"
            resolved_api_key = os.environ.get(env_var, "").strip()
            if not resolved_api_key:
                raise ValueError(
                    f"Missing API key for provider {resolved_provider!r}. "
                    f"Pass `api_key` or set {env_var}."
                )

        if clean_model is None:
            if config is None:
                raise ValueError(
                    f"No default model configured for provider {resolved_provider!r}; "
                    "please specify `model`."
                )
            normalized_model = config.default_model
        elif "/" not in clean_model:
            normalized_model = f"{resolved_provider}/{clean_model}"
        else:
            normalized_model = clean_model

        return resolved_provider, normalized_model, resolved_api_key

    @staticmethod
    def _build_response_format(
        json_schema: dict[str, Any] | type[BaseModel] | None,
    ) -> dict[str, Any] | type[BaseModel] | None:
        """Convert a JSON schema dict or Pydantic model into LiteLLM `response_format`."""

        raise NotImplementedError

    @staticmethod
    def _normalize_tools(
        tools: list[dict[str, Any]] | None,
    ) -> list[dict[str, Any]] | None:
        """Normalize tool schemas to OpenAI/LiteLLM `{"type": "function", ...}` format."""
        raise NotImplementedError

    @staticmethod
    def _parse_response(
        response: Any,
        json_schema: dict[str, Any] | type[BaseModel] | None = None,
    ) -> ProviderResponse:
        """Convert a LiteLLM `ModelResponse` into a standardized `ProviderResponse`"""
        raise NotImplementedError

    async def complete(
        self,
        messages: list[dict[str, Any]],
        *,
        json_schema: dict[str, Any] | type[BaseModel] | None = None,
        tools: list[dict[str, Any]] | None = None,
        temperature: float | None = None,
        **kwargs: Any,
    ) -> ProviderResponse:
        """Perform a single non-streaming LLM call."""
        raise NotImplementedError

    async def stream(
        self,
        messages: list[dict[str, Any]],
        *,
        json_schema: dict[str, Any] | type[BaseModel] | None = None,
        tools: list[dict[str, Any]] | None = None,
        temperature: float | None = None,
        **kwargs: Any,
    ) -> AsyncIterator[StreamChunk]:
        """Stream an LLM response chunk by chunk."""
        raise NotImplementedError
